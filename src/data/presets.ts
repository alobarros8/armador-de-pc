// Chequeo en desarrollo: detecta presets que apuntan a componentes inexistentes.
if (import.meta.env.DEV) {
  const ids = new Set<string>()
  import('./catalog').then(({ PARTS }) => {
    PARTS.forEach((part) => ids.add(part.id))
    for (const preset of PRESETS) {
      for (const list of Object.values(preset.selections)) {
        for (const id of list ?? []) {
          if (!ids.has(id)) console.warn(`[presets] ${preset.id}: falta el componente "${id}"`)
        }
      }
    }
  })
}
